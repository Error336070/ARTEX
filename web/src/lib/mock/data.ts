// assetRef converts an asset ID to a finding asset reference. Labels match backend coverageNodeLabel:
// URL > domain > IP > application name. The asset view uses these references
// to attach findings to assets.
function assetRef(id: number): FindingAsset {
  const asset = assets.find((candidate) => candidate.id === id);
  if (!asset) throw new Error(`mock assetRef: unknown asset ${id}`);
  return {
    id: String(id),
    type: asset.type,
    label: asset.url || asset.domain || asset.ip || asset.app_name || String(id),
  };
}

